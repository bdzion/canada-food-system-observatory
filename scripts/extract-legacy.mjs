// Copies the stress-test model code, unchanged, from the pinned legacy page
// (reference/legacy-index.html, commit in reference/LEGACY_SHA) into an ES module.
// The regression test runs the same code straight from the legacy page and
// checks that the migrated module gives identical results.
import { readFileSync, writeFileSync } from "node:fs";

export const BLOCKS = [
  ["/* ---------- helpers ---------- */", "/* ---------- state ---------- */"],
  ["const NODES = [", "const NODE_OVERRIDE = "],
  // Decision game (rail closure): state machine and cost model.
  ["const GX = ", "function corridorSVG("],
  ["const GCAT = ", "function buildChallenge("],
];
export const EXPORTS = [
  "SCEN", "MODELLED", "MODEL_CARDS", "MODEL_CAT", "CATS", "PATHS", "ORIGIN", "SIG", "TREND", "REG",
  "UPDATES", "NOTES", "STORIES", "SNAPSHOT", "VERSION", "CHECKED", "NODES", "PATH_NODE", "LEVEL",
  "INDIC", "TIMELINES", "KIND", "fmtM", "dayToDate", "fmtDay", "clamp", "esc",
  "GX", "GC", "GPATHS", "GWORST", "GPLANS0", "fmtCM", "gOpts5", "gSim", "GCOMP", "GNONE", "gPlanName",
  "GCAT", "GCOST_SRC", "gMetrics", "gDebrief",
];

export function legacyCode(html) {
  const script = html.slice(html.indexOf("<script>") + 8);
  return BLOCKS.map(([a, b]) => {
    const i = script.indexOf(a), j = script.indexOf(b, i);
    if (i < 0 || j < 0) throw new Error("legacy block not found: " + a);
    return script.slice(i, j);
  }).join("\n")
    // The only DOM-dependent helpers; they are never called by the models.
    .replace(/^const \$ = .*$/m, "")
    .replace(/^const css = .*$/m, "");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const sha = readFileSync("reference/LEGACY_SHA", "utf8").trim();
  const code = legacyCode(readFileSync("reference/legacy-index.html", "utf8"));
  const out = `// @ts-nocheck
/* Generated by scripts/extract-legacy.mjs — do not edit by hand.
 * Source: github.com/bdzion/canada-food-stress-test, index.html at commit ${sha}.
 * Model equations, assumptions, threat register and storylines are copied unchanged.
 * Warning levels and risk scores in REG are the authors' preliminary judgement. */
${code}
export { ${EXPORTS.join(", ")} };
`;
  writeFileSync("src/legacy/core.js", out);
  console.log("wrote src/legacy/core.js", out.length, "bytes");
}
